/** Locale currently driving i18n-js. Unknown values fall back to the zh-Hant default. */
export function getI18nLocale(): Locale {
  return i18n.locale === 'en' ? 'en' : 'zh-Hant';
}

export function t(key: string, params?: Record<string, string | number>): string {
  const value = i18n.t(key, params);
  // Guard against accidentally addressing a parent node in the nested dictionary.
  return typeof value === 'string' ? value : key;
}
