export const dictionaries: Record<Locale, Dictionary> = {
  'zh-Hant': zhHant,
  en,
};

export function isLocale(value: unknown): value is Locale {
  return value === 'zh-Hant' || value === 'en';
}

export function readStoredLocale(): Locale {
  try {
    const stored = window.localStorage.getItem(LOCALE_STORAGE_KEY);
    if (isLocale(stored)) return stored;
  } catch {
    /* localStorage unavailable (private mode / non-browser) */
  }
  return DEFAULT_LOCALE;
}

function interpolate(template: string, vars?: Vars): string {
  if (!vars) return template;
  return template.replace(/\{(\w+)\}/g, (match, name: string) =>
    Object.prototype.hasOwnProperty.call(vars, name) ? String(vars[name]) : match,
  );
}

export function translate(locale: Locale, key: string, vars?: Vars, fallback?: string): string {
  const dictionary = dictionaries[locale];
  const defaultDictionary = dictionaries[DEFAULT_LOCALE];
  let template = dictionary[key] ?? defaultDictionary[key];
  // Simple singular support: when the caller passes `count: 1`, prefer `key.one`
  // when both dictionaries define it (used for English pluralisation).
  if (vars && vars.count === 1) {
    template = dictionary[`${key}.one`] ?? defaultDictionary[`${key}.one`] ?? template;
  }
  if (template === undefined) return fallback ?? key;
  return interpolate(template, vars);
}

// Module-level active locale so non-React modules (API layer, mock data, formatters)
// can resolve strings without a hook.
let activeLocale: Locale = DEFAULT_LOCALE;

export function getActiveLocale(): Locale {
  return activeLocale;
}

/** Translate using the active locale from outside React (api.ts, useAsync.ts). */
export function translateCurrent(key: string, vars?: Vars, fallback?: string): string {
  return translate(activeLocale, key, vars, fallback);
}

export type TFunction = (key: string, vars?: Vars, fallback?: string) => string;

interface I18nContextValue {
  locale: Locale;
  setLocale: (locale: Locale) => void;
  t: TFunction;
}

const I18nContext = createContext<I18nContextValue | null>(null);

export function LanguageProvider({ children }: { children: React.ReactNode }) {
  const [locale, setLocaleState] = useState<Locale>(() => readStoredLocale());

  // Keep non-React consumers (mock data + date formatters) in sync before children
  // render, so a language switch repaints every string in the same commit.
  activeLocale = locale;
  setFormatLocale(locale);

  const setLocale = useCallback((next: Locale) => {
    setLocaleState(next);
  }, []);

  useEffect(() => {
    document.documentElement.lang = locale;
    document.title = translate(locale, 'common.appTitle');
    try {
      window.localStorage.setItem(LOCALE_STORAGE_KEY, locale);
    } catch {
      /* persistence is best-effort */
    }
  }, [locale]);

  const t = useCallback<TFunction>((key, vars, fallback) => translate(locale, key, vars, fallback), [locale]);

  const value = useMemo(() => ({ locale, setLocale, t }), [locale, setLocale, t]);

  return <I18nContext.Provider value={value}>{children}</I18nContext.Provider>;
}

export function useI18n(): I18nContextValue {
  const ctx = useContext(I18nContext);
  if (!ctx) throw new Error('useI18n must be used inside LanguageProvider');
  return ctx;
}
